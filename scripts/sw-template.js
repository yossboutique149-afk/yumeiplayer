/**
 * Service worker source generator.
 *
 * Kept as a plain string template so `tests/offline.test.js` can assert the
 * offline strategy without starting a browser. `scripts/build-sw.mjs` fills in
 * the real precache list and a content hash after every `vite build`.
 */
export function serviceWorkerSource({ version, precache }) {
  const files = JSON.stringify(precache, null, 2);

  return `/* YUMEIKA offline service worker — generated by scripts/build-sw.mjs.
 * Cache version is a hash of the built files, so a new build installs a new
 * shell and the old caches are removed on activation.
 */
const VERSION = ${JSON.stringify(version)};
const SHELL_CACHE = "yumeika-shell-" + VERSION;
const RUNTIME_CACHE = "yumeika-runtime-" + VERSION;
const PRECACHE = ${files};

const AUDIO_EXTENSIONS = /\\.(mp3|m4a|ogg|wav|flac)$/i;

self.addEventListener("install", event => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(SHELL_CACHE);
      // addAll() rejects the whole batch on one 404, so cache one by one.
      await Promise.all(
        PRECACHE.map(async url => {
          try {
            await cache.add(new Request(url, { cache: "reload" }));
          } catch (error) {
            /* a single missing asset must not break the offline install */
          }
        })
      );
      await self.skipWaiting();
    })()
  );
});

self.addEventListener("activate", event => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(
        keys
          .filter(key => key !== SHELL_CACHE && key !== RUNTIME_CACHE)
          .map(key => caches.delete(key))
      );
      await self.clients.claim();
    })()
  );
});

self.addEventListener("message", event => {
  if (event.data && event.data.type === "SKIP_WAITING") {
    self.skipWaiting();
  }
});

async function cachedResponse(url) {
  const cache = await caches.open(SHELL_CACHE);
  return (await cache.match(url)) || (await caches.match(url));
}

/* Range requests are what <audio> uses, and a partial response cannot be
 * cached as-is. Serve the byte slice from the precached full file so uploaded
 * audio keeps working (and seeking keeps working) with no network. */
async function serveAudio(request, url) {
  const cached = await cachedResponse(url);
  if (!cached) return fetch(request);

  const range = request.headers.get("range");
  if (!range) return cached;

  const match = /bytes=(\\d*)-(\\d*)/.exec(range);
  if (!match) return cached;

  const buffer = await cached.arrayBuffer();
  const total = buffer.byteLength;
  const start = match[1] ? Number(match[1]) : 0;
  const end = match[2] ? Math.min(Number(match[2]), total - 1) : total - 1;

  if (Number.isNaN(start) || start >= total || end < start) {
    return new Response(null, {
      status: 416,
      headers: { "Content-Range": "bytes */" + total }
    });
  }

  const slice = buffer.slice(start, end + 1);
  return new Response(slice, {
    status: 206,
    statusText: "Partial Content",
    headers: {
      "Content-Type": cached.headers.get("Content-Type") || "audio/mpeg",
      "Content-Range": "bytes " + start + "-" + end + "/" + total,
      "Content-Length": String(slice.byteLength),
      "Accept-Ranges": "bytes"
    }
  });
}

self.addEventListener("fetch", event => {
  const { request } = event;
  if (request.method !== "GET") return;

  const url = new URL(request.url);
  const sameOrigin = url.origin === self.location.origin;

  // Live API, Supabase and every third party (Spotify/YouTube embeds) stay online-only.
  if (!sameOrigin || url.pathname.startsWith("/api/")) return;

  if (request.mode === "navigate") {
    event.respondWith(
      (async () => {
        try {
          const response = await fetch(request);
          const cache = await caches.open(SHELL_CACHE);
          cache.put("/index.html", response.clone());
          return response;
        } catch (error) {
          const fallback =
            (await cachedResponse("/index.html")) ||
            (await cachedResponse("/")) ||
            (await cachedResponse("/offline"));
          return fallback || Response.error();
        }
      })()
    );
    return;
  }

  if (AUDIO_EXTENSIONS.test(url.pathname) || request.headers.get("range")) {
    event.respondWith(serveAudio(request, url.pathname));
    return;
  }

  event.respondWith(
    (async () => {
      const cached = await caches.match(request);
      if (cached) return cached;
      try {
        const response = await fetch(request);
        if (response.ok && response.type === "basic") {
          const cache = await caches.open(RUNTIME_CACHE);
          cache.put(request, response.clone());
        }
        return response;
      } catch (error) {
        return cached || Response.error();
      }
    })()
  );
});
`;
}
